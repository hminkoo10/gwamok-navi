/** 묶음과 세부 학과 모두 (저장된 선택·공유 링크·AI 결과 검사에 쓴다) */
export const MAJOR_BY_ID = new Map<string, Major>([...MAJORS, ...FINE_MAJORS].map((m) => [m.id, m]))

/** 저장된 분야 id를 지금 id로 바꾼다 (없어진 id는 새 id로 풀고, 모르는 id는 뺀다) */
export function upgradeMajors(ids: string[]): string[] {
  return [...new Set(ids.flatMap((id) => MAJOR_ALIASES[id] ?? [id]))].filter((id) => MAJOR_BY_ID.has(id))
}
