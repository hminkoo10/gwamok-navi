const COARSE = new Map(MAJORS.map((m) => [m.id, m]))

/**
 * 세부 학과. 묶음(계열) 안에서 모집단위 이름으로 나눈다.
 * match는 띄어쓰기·가운뎃점·괄호를 뺀 소문자 모집단위 이름에 건다 (engine/search의 norm).
 * 어느 세부 학과에도 들지 않는 넓은 모집단위(공과대학, 자연계열 전 모집단위 등)는 그 묶음의 세부 학과를 고르면 함께 나온다.
 */
export interface FineMajor extends Major {
  parent: string
  match: RegExp
  /** 진로 관련도를 셀 때 함께 보는 가까운 학과(세부 학과 id 또는 묶음 id). 예: 컴퓨터교육 → 컴퓨터공학 */
  related?: string[]
}

const f = (id: string, name: string, parent: string, match: RegExp, keywords: string[] = [], related?: string[]): FineMajor => ({
  id,
  name,
  parent,
  field: COARSE.get(parent)!.field,
  match,
  keywords,
  ...(related ? { related } : {}),
})

